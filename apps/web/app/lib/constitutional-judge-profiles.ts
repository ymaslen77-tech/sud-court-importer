export const constitutionalJudgeProfileHref=(id:string):string=>{
 const career=CONSTITUTIONAL_JUDGE_CAREERS.find(c=>c.id===id);
 return career?'/judges/'+CONSTITUTIONAL_JUDGE_REGION+'/'+career.slug:'/judges';
};
export const constitutionalJudgeProfiles=CONSTITUTIONAL_JUDGE_CAREERS.map(career=>{
 const judge=CONSTITUTIONAL_JUDGES.find(j=>j.id===career.id);
 if(!judge)throw new Error('Missing official judge roster '+career.id);
 return {...judge,...career,sourceCheckedAt:'2026-10-29'};
});
export type ConstitutionalJudgeProfile=(typeof constitutionalJudgeProfiles)[number];
export const findConstitutionalJudgeProfile=(slug:string)=>
 constitutionalJudgeProfiles.find(j=>j.slug===slug);
